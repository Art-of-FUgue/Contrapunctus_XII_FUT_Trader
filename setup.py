"""
One-command initialisation of the card data: pages/, defs/, players.json, holo_ids.json.

    python setup.py                 # safe to run again and again; it reports what is missing
    python setup.py --download      # also fetch the fut.gg list pages for you (opt-in, see below)

What it does, in order
  1. Creates the pages/ and defs/ folders.
  2. pages/  : needs the saved fut.gg special-card list pages (page_001.json, ...).
               Save them by hand, or use --download.
  3. defs/   : holo cards are separate EA ids that the list hides. This reads fut.gg's
               public price index (the same static file the scanner uses), works out which
               ids are not in your list yet, and WRITES holo_lookup_console.js with that
               fresh id list inside. Paste that script into the browser console on any
               fut.gg page; it downloads defs_01.json; put that file in defs/.
  4. Builds players.json and holo_ids.json (via build_players.py) from pages/ + defs/.
  5. Prints a status summary and the next step.

Run it once to get the console script, then again after saving defs_01.json.

--download uses fut.gg's /api/ list endpoint, which its robots.txt asks bots not to use.
It is opt-in, slow (5 s between pages) and meant to be run rarely; check fut.gg's terms
first, or save the pages by hand instead. Nothing else here calls /api/.
"""
import argparse
import glob
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build_players as bp                        # noqa: E402

DEFS_DIR = bp.DEFS_DIR
PAGES_DIR = bp.PAGES_DIR
CONSOLE_JS = os.path.join(HERE, "holo_lookup_console.js")
R2 = "https://r2.fut.gg/27/"
HEADERS = {"Referer": "https://www.fut.gg/", "User-Agent": "Mozilla/5.0 (personal price alert bot)"}
HOLO_ID_FLOOR = 60_000_000        # holo and newer special cards have ids in this range

JS_TEMPLATE = r'''// Generated by setup.py. Run in the DevTools Console on any https://www.fut.gg page
// (type "allow pasting" first if the console asks). Looks up __COUNT__ card ids in small
// batches, slowly, and downloads defs_01.json. Put that file in the defs/ folder.
(async () => {
  const ids = __IDS__;
  const base = "https://www.fut.gg/api/fut/players/v2/definition-data/?game=27&slugs=";
  const out = [];
  let size = 25, i = 0;
  while (i < ids.length) {
    const batch = ids.slice(i, i + size);
    const r = await fetch(base + batch.map(x => "27-" + x).join(","), {credentials: "same-origin"});
    if (!r.ok) {
      const t = await r.text();
      if (size > 1 && /many|limit|max/i.test(t)) { size = Math.max(1, Math.floor(size / 2)); console.log("batch too big, now", size); continue; }
      console.error("stopped:", r.status, t.slice(0, 200)); break;
    }
    const j = await r.json();
    out.push(...(j.data || []));
    i += batch.length;
    console.log(i + "/" + ids.length, "records:", out.length);
    await new Promise(res => setTimeout(res, 1500));
  }
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([JSON.stringify({data: out})], {type: "application/json"}));
  a.download = "defs_01.json";
  a.click();
  console.log("done, saved", out.length, "records");
})();
'''


def fetch_json(url: str):
    req = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def price_index_ids() -> list[int]:
    """All card ids in fut.gg's public price index (delta-encoded sorted ids)."""
    manifest = fetch_json(R2 + "manifest.json")
    idx = fetch_json(f"{R2}player-prices-index.v1.{manifest['player-prices-index']}.json")
    ids = [idx["id0"]]
    for gap in idx["d"]:
        ids.append(ids[-1] + gap)
    return ids


def list_ids() -> set[int]:
    ids: set[int] = set()
    for fp in glob.glob(os.path.join(PAGES_DIR, "*.json")) + glob.glob(os.path.join(PAGES_DIR, "*.txt")):
        try:
            ids |= {row["eaId"] for row in bp.load_page(fp)["data"]}
        except (ValueError, KeyError, TypeError):
            pass
    return ids


def write_console_script(candidates: list[int]) -> None:
    js = JS_TEMPLATE.replace("__COUNT__", str(len(candidates))).replace("__IDS__", json.dumps(candidates))
    with open(CONSOLE_JS, "w", encoding="utf-8") as f:
        f.write(js)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--download", action="store_true", help="fetch the fut.gg list pages (opt-in)")
    ap.add_argument("--max-pages", type=int, default=100)
    ap.add_argument("--delay", type=float, default=5.0)
    args = ap.parse_args()

    os.makedirs(PAGES_DIR, exist_ok=True)
    os.makedirs(DEFS_DIR, exist_ok=True)
    print(f"folders ready: {PAGES_DIR}\n               {DEFS_DIR}")

    # 2. list pages
    if args.download:
        bp.download(args.max_pages, args.delay)
    pages = glob.glob(os.path.join(PAGES_DIR, "*.json")) + glob.glob(os.path.join(PAGES_DIR, "*.txt"))
    if not pages:
        print("\nSTEP 1 NEEDED: no list pages in pages/.")
        print("  Save each page into pages/ (Ctrl+S), for page = 1, 2, 3 ... until \"next\":null:")
        print("  https://www.fut.gg/api/fut/players/v2/27/?page=1&quality_id=10&response_format=card-image")
        print("  (or run: python setup.py --download). Then run setup.py again.")
        return

    # 3. holo lookup script with a fresh id list
    known = list_ids()
    defs = glob.glob(os.path.join(DEFS_DIR, "*.json")) + glob.glob(os.path.join(DEFS_DIR, "*.txt"))
    try:
        candidates = [i for i in price_index_ids() if i >= HOLO_ID_FLOOR and i not in known]
        write_console_script(candidates)
        print(f"\nholo lookup script written: {CONSOLE_JS} ({len(candidates)} candidate ids)")
    except Exception as e:                          # offline or fut.gg changed: keep the old script
        print(f"\n[warn] could not read the price index ({str(e)[:80]}); "
              f"{'keeping the existing' if os.path.exists(CONSOLE_JS) else 'no'} holo lookup script")

    # 4. build players.json + holo_ids.json
    print()
    bp.merge()

    # 5. status
    holo_ids = []
    if os.path.exists(bp.HOLO_OUT):
        with open(bp.HOLO_OUT, encoding="utf-8") as f:
            holo_ids = json.load(f)
    with open(bp.OUT, encoding="utf-8") as f:
        total = len(json.load(f)["data"])
    print("\n---- status ----")
    print(f"players.json : {total} cards")
    print(f"holo_ids.json: {len(holo_ids)} holo cards" if defs else "holo_ids.json: not built yet (no defs/ files)")
    if not defs:
        print("\nSTEP 2 NEEDED (holo cards):")
        print("  1) open any fut.gg page, press F12, open the Console")
        print(f"  2) paste the contents of {os.path.basename(CONSOLE_JS)} and press Enter, wait for \"done\"")
        print("  3) put the downloaded defs_01.json in the defs/ folder")
        print("  4) run: python setup.py")
    else:
        print("\nDone. Commit players.json and holo_ids.json (and the scripts) to GitHub.")


if __name__ == "__main__":
    main()
